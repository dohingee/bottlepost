package com.bottlepost.app.auth

import android.content.Context
import androidx.credentials.CredentialManager
import androidx.credentials.CustomCredential
import androidx.credentials.GetCredentialRequest
import androidx.credentials.exceptions.GetCredentialCancellationException
import com.bottlepost.app.R
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential
import com.google.firebase.auth.AuthCredential
import com.google.firebase.auth.FirebaseAuth
import com.google.firebase.auth.FirebaseAuthUserCollisionException
import com.google.firebase.auth.GoogleAuthProvider
import kotlinx.coroutines.tasks.await

sealed interface GoogleResult {
    /** The anonymous account now has Google attached; same uid, nothing to restore. */
    data object Linked : GoogleResult
    /** This Google account already belonged to an earlier install; we switched to it. Restore the backup. */
    data object SwitchedToExisting : GoogleResult
    data object Cancelled : GoogleResult
}

/**
 * Starts every install as an anonymous Firebase user (no sign-in needed to use the app), and lets the
 * user attach Google later so the account survives reinstalling or switching phones.
 */
class AuthManager(private val auth: FirebaseAuth = FirebaseAuth.getInstance()) {

    val uid: String? get() = auth.currentUser?.uid
    val isGoogleLinked: Boolean
        get() = auth.currentUser?.providerData?.any { it.providerId == GoogleAuthProvider.PROVIDER_ID } == true

    suspend fun ensureSignedIn(): String = auth.currentUser?.uid ?: auth.signInAnonymously().await().user!!.uid

    /**
     * [activityContext] must be an Activity so Credential Manager can show its bottom sheet.
     * [discardCurrent] removes the fresh anonymous account (server data included) when the Google
     * account turns out to belong to an earlier install.
     */
    suspend fun connectGoogle(activityContext: Context, discardCurrent: suspend () -> Unit): GoogleResult {
        val credential = try {
            googleCredential(activityContext)
        } catch (_: GetCredentialCancellationException) {
            return GoogleResult.Cancelled
        }
        val current = auth.currentUser
        if (current == null) {
            auth.signInWithCredential(credential).await()
            return GoogleResult.SwitchedToExisting
        }
        return try {
            current.linkWithCredential(credential).await()
            // Refresh the ID token so the server sees the google.com provider and e-mail.
            current.getIdToken(true).await()
            GoogleResult.Linked
        } catch (_: FirebaseAuthUserCollisionException) {
            // Reinstall / new phone: the Google account is attached to the old uid. The fresh anonymous
            // user has nothing worth keeping, so delete it and continue as the old account.
            runCatching { discardCurrent() }.onFailure { runCatching { current.delete().await() } }
            auth.signInWithCredential(credential).await()
            GoogleResult.SwitchedToExisting
        }
    }

    private suspend fun googleCredential(activityContext: Context): AuthCredential {
        // default_web_client_id is generated by the google-services plugin from google-services.json.
        val option = GetSignInWithGoogleOption.Builder(activityContext.getString(R.string.default_web_client_id)).build()
        val request = GetCredentialRequest.Builder().addCredentialOption(option).build()
        val result = CredentialManager.create(activityContext).getCredential(activityContext, request)
        val cred = result.credential
        check(cred is CustomCredential && cred.type == GoogleIdTokenCredential.TYPE_GOOGLE_ID_TOKEN_CREDENTIAL) {
            "Unexpected credential type"
        }
        return GoogleAuthProvider.getCredential(GoogleIdTokenCredential.createFrom(cred.data).idToken, null)
    }

    fun signOut() = auth.signOut()
}
